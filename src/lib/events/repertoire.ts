const FALLBACK: Partial<Record<Category, string>> = {
  house: "House",
  rave: "EDM",
};

export function actProfile(title: string, category: Category): ActProfile | undefined {
  const hay = title.toLowerCase().replace(/[’‘]/g, "'");
  for (const [needle, profile] of ACTS) {
    if (hay.includes(needle)) return profile;
  }
  const fallback = FALLBACK[category];
  return fallback ? { styles: fallback } : undefined;
}
